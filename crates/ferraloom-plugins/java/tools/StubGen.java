import java.io.IOException;
import java.lang.reflect.GenericArrayType;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.lang.reflect.TypeVariable;
import java.lang.reflect.WildcardType;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.StringJoiner;

/**
 * Writes the bridge's stubs from the API jar: for each interface (or abstract
 * class) named, a class {@code dev.ferraloom.bukkit.stub.Stub<Name>} that
 * implements every abstract method by throwing
 * {@code UnsupportedOperationException} naming the method. The bridge's classes extend these and override what they implement,
 * so a method Ferraloom lacks fails loudly, and a new API method compiles
 * without anyone writing it by hand.
 *
 * <pre>java -cp spigot-api.jar:tools StubGen OUT_DIR org.bukkit.Server org.bukkit.entity.Player ...</pre>
 */
public final class StubGen {
    private static final String PACKAGE = "dev.ferraloom.bukkit.stub";

    public static void main(String[] args) throws Exception {
        Path out = Path.of(args[0]).resolve(PACKAGE.replace('.', '/'));
        Files.createDirectories(out);
        for (int i = 1; i < args.length; i++) {
            Class<?> type = Class.forName(args[i], false, StubGen.class.getClassLoader());
            if (!type.isInterface() && !Modifier.isAbstract(type.getModifiers())) {
                throw new IllegalArgumentException(args[i] + " is not an interface or an abstract class");
            }
            Files.writeString(out.resolve(stubName(type) + ".java"), stub(type));
        }
    }

    /** {@code Player} → {@code StubPlayer}; a nested {@code Foo.Bar} → {@code StubFoo_Bar}. */
    static String stubName(Class<?> type) {
        String binary = type.getName().substring(type.getPackageName().length() + 1);
        return "Stub" + binary.replace('$', '_');
    }

    static String stub(Class<?> type) throws IOException {
        Map<TypeVariable<?>, Type> bindings = new HashMap<>();
        bind(type, bindings);
        StringBuilder s = new StringBuilder();
        s.append("// Generated by crates/ferraloom-plugins/java/tools/StubGen.java from the Spigot API jar. Do not edit.\n");
        s.append("package ").append(PACKAGE).append(";\n\n");
        s.append("/** Every abstract method of {@link ").append(type.getCanonicalName())
                .append("}, unsupported until Ferraloom overrides it. */\n");
        s.append("@SuppressWarnings({\"deprecation\", \"removal\", \"unchecked\", \"rawtypes\"})\n");
        s.append("public class ").append(stubName(type)).append(type.isInterface() ? " implements " : " extends ")
                .append(type.getCanonicalName()).append(" {\n");
        for (Method m : methods(type)) {
            s.append(method(type, m, bindings));
        }
        s.append("}\n");
        return s.toString();
    }

    /** The interface's type variables as its supertypes see them, so inherited generic methods render resolved. */
    static void bind(Class<?> type, Map<TypeVariable<?>, Type> bindings) {
        for (Type parent : type.getGenericInterfaces()) {
            if (parent instanceof ParameterizedType p && p.getRawType() instanceof Class<?> raw) {
                TypeVariable<?>[] vars = raw.getTypeParameters();
                Type[] args = p.getActualTypeArguments();
                for (int i = 0; i < vars.length; i++) {
                    bindings.put(vars[i], resolve(args[i], bindings));
                }
                bind(raw, bindings);
            } else if (parent instanceof Class<?> raw) {
                bind(raw, bindings);
            }
        }
    }

    static Type resolve(Type t, Map<TypeVariable<?>, Type> bindings) {
        Type seen = t;
        while (seen instanceof TypeVariable<?> v && bindings.containsKey(v)) {
            seen = bindings.get(v);
        }
        return seen;
    }

    /**
     * The methods a class implementing the interface must define: abstract
     * ones (not Object's), one per signature, with the most specific return
     * type, skipping a signature some interface already gives a default for.
     */
    static List<Method> methods(Class<?> type) {
        Map<String, List<Method>> bySignature = new LinkedHashMap<>();
        for (Method m : type.getMethods()) {
            // javac's covariant-return bridges are synthetic defaults: they implement nothing a class must.
            if (Modifier.isStatic(m.getModifiers()) || m.isBridge() || m.isSynthetic() || isObjectMethod(m)) {
                continue;
            }
            bySignature.computeIfAbsent(m.getName() + Arrays.toString(m.getParameterTypes()), k -> new ArrayList<>()).add(m);
        }
        List<Method> chosen = new ArrayList<>();
        for (List<Method> group : bySignature.values()) {
            if (group.stream().noneMatch(m -> Modifier.isAbstract(m.getModifiers()))) {
                continue;
            }
            // An abstract class's own method implements its interfaces' one.
            if (group.stream().anyMatch(m -> !m.getDeclaringClass().isInterface() && !Modifier.isAbstract(m.getModifiers()))) {
                continue;
            }
            if (group.stream().anyMatch(m -> m.isDefault() && overridesAll(m, group))) {
                continue;
            }
            Method best = group.get(0);
            for (Method m : group) {
                if (best.getReturnType().isAssignableFrom(m.getReturnType())) {
                    best = m;
                }
            }
            chosen.add(best);
        }
        chosen.sort((a, b) -> {
            int c = a.getName().compareTo(b.getName());
            return c != 0 ? c : Arrays.toString(a.getParameterTypes()).compareTo(Arrays.toString(b.getParameterTypes()));
        });
        return chosen;
    }

    /** A default method wins when its interface extends every other declaring interface of the signature. */
    static boolean overridesAll(Method m, List<Method> group) {
        for (Method other : group) {
            if (!other.getDeclaringClass().isAssignableFrom(m.getDeclaringClass())) {
                return false;
            }
        }
        return true;
    }

    static boolean isObjectMethod(Method m) {
        try {
            Object.class.getMethod(m.getName(), m.getParameterTypes());
            return true;
        } catch (NoSuchMethodException e) {
            return false;
        }
    }

    static String method(Class<?> type, Method m, Map<TypeVariable<?>, Type> bindings) {
        StringBuilder s = new StringBuilder("\n    @Override\n    public ");
        TypeVariable<Method>[] vars = m.getTypeParameters();
        if (vars.length > 0) {
            StringJoiner j = new StringJoiner(", ", "<", "> ");
            for (TypeVariable<Method> v : vars) {
                StringJoiner bounds = new StringJoiner(" & ");
                for (Type b : v.getBounds()) {
                    if (b != Object.class) {
                        bounds.add(render(b, bindings));
                    }
                }
                j.add(bounds.length() == 0 ? v.getName() : v.getName() + " extends " + bounds);
            }
            s.append(j);
        }
        s.append(render(m.getGenericReturnType(), bindings)).append(' ').append(m.getName()).append('(');
        Type[] params = m.getGenericParameterTypes();
        StringJoiner names = new StringJoiner(", ");
        for (int i = 0; i < params.length; i++) {
            String p = render(params[i], bindings);
            if (m.isVarArgs() && i == params.length - 1) {
                p = p.substring(0, p.length() - 2) + "...";
            }
            s.append(i == 0 ? "" : ", ").append(p).append(" arg").append(i);
            names.add(m.getParameterTypes()[i].getSimpleName());
        }
        s.append(')');
        Type[] thrown = m.getGenericExceptionTypes();
        for (int i = 0; i < thrown.length; i++) {
            s.append(i == 0 ? " throws " : ", ").append(render(thrown[i], bindings));
        }
        s.append(" {\n        throw new UnsupportedOperationException(\"Ferraloom does not implement ")
                .append(type.getSimpleName()).append('.').append(m.getName()).append('(').append(names)
                .append(") yet\");\n    }\n");
        return s.toString();
    }

    /** A type as source: canonical names, generics resolved, wildcards and arrays. */
    static String render(Type t, Map<TypeVariable<?>, Type> bindings) {
        t = resolve(t, bindings);
        if (t instanceof Class<?> c) {
            return c.isArray() ? render(c.getComponentType(), bindings) + "[]" : c.getCanonicalName();
        }
        if (t instanceof ParameterizedType p) {
            StringJoiner args = new StringJoiner(", ", "<", ">");
            for (Type a : p.getActualTypeArguments()) {
                args.add(render(a, bindings));
            }
            return render(p.getRawType(), bindings) + args;
        }
        if (t instanceof WildcardType w) {
            if (w.getLowerBounds().length > 0) {
                return "? super " + render(w.getLowerBounds()[0], bindings);
            }
            Type upper = w.getUpperBounds()[0];
            return upper == Object.class ? "?" : "? extends " + render(upper, bindings);
        }
        if (t instanceof GenericArrayType g) {
            return render(g.getGenericComponentType(), bindings) + "[]";
        }
        if (t instanceof TypeVariable<?> v) {
            return v.getName();
        }
        throw new IllegalArgumentException("Unknown type " + t);
    }
}
