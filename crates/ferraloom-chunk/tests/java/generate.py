#!/usr/bin/env python3
"""Regenerate numeric tests using the shared official jar; never starts a server."""
import os
from pathlib import Path
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
VANILLA = Path(os.environ.get("FERRALOOM_VANILLA_DIR", "/home/doc/code/Ferraloom/.cache/vanilla/26.3"))
JDK = Path(os.environ.get("JAVA_HOME", "/home/doc/code/Ferraloom/.cache/toolchains/jdk-25.0.4.1+1"))
CLASSPATH = ":".join(map(str, [VANILLA / "versions/26.3/server-26.3.jar", *sorted((VANILLA / "libraries").rglob("*.jar"))]))
with tempfile.TemporaryDirectory(prefix="ferraloom-chunk-java-") as directory:
    subprocess.run([str(JDK / "bin/javac"), "-cp", CLASSPATH, "-d", directory, str(HERE / "ChunkVectors.java")], check=True, cwd=directory)
    result = subprocess.run([str(JDK / "bin/java"), "-cp", directory + ":" + CLASSPATH, "ChunkVectors"], cwd=directory, capture_output=True, text=True)
    if result.returncode:
        raise SystemExit(result.stdout + result.stderr)
    vectors = result.stdout.split("// BEGIN CHUNK VECTORS\n", 1)[1]
    (HERE / "../../src/vanilla_vectors.rs").write_text("// Generated by tests/java/ChunkVectors.java against vanilla 26.3.\n" + vectors)
