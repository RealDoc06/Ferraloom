#!/usr/bin/env python3
"""Regenerate numeric Rust vectors using the shared, unmodified vanilla cache.

This is light Java work on devbox. Rust builds/tests still use ferraloom-build.
Override FERRALOOM_VANILLA_DIR and JAVA_HOME when the caches live elsewhere.
"""
import os
from pathlib import Path
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
VANILLA = Path(os.environ.get("FERRALOOM_VANILLA_DIR", "/home/doc/code/Ferraloom/.cache/vanilla/26.3"))
JDK = Path(os.environ.get("JAVA_HOME", "/home/doc/code/Ferraloom/.cache/toolchains/jdk-25.0.4.1+1"))
CLASSPATH = ":".join(map(str, [VANILLA / "versions/26.3/server-26.3.jar", *sorted((VANILLA / "libraries").rglob("*.jar"))]))
with tempfile.TemporaryDirectory(prefix="ferraloom-util-java-") as directory:
    subprocess.run([str(JDK / "bin/javac"), "-cp", CLASSPATH, "-d", directory, str(HERE / "VanillaVectors.java")], check=True, cwd=directory)
    result = subprocess.run([str(JDK / "bin/java"), "-cp", directory + ":" + CLASSPATH, "VanillaVectors"], check=True, cwd=directory, capture_output=True, text=True)
    vectors = result.stdout[result.stdout.index("pub const RNG:"):]
    (HERE / "../../src/vanilla_vectors.rs").write_text("// Generated by tests/java/VanillaVectors.java against vanilla 26.3.\n" + vectors)
