use super::*;
fn bytes(hex: &str) -> Vec<u8> {
    let hex = hex.trim();
    (0..hex.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap())
        .collect()
}
fn check<T: Wire>(name: &str, hex: &str) {
    let expected = bytes(hex);
    let value = T::from_bytes(&expected).unwrap_or_else(|e| panic!("{name}: {e}"));
    assert_eq!(value.to_bytes().unwrap(), expected, "{name}");
}
