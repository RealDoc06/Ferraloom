use super::*;
struct Context {
    entries: Vec<(String, i32, String)>,
}
impl Context {
    fn new() -> Self {
        let data: serde_json::Value =
            serde_json::from_str(include_str!("../../../../data/generated/registries.json"))
                .unwrap();
        let mut entries = Vec::new();
        for (registry, value) in data.as_object().unwrap() {
            for (key, value) in value["entries"].as_object().unwrap() {
                entries.push((
                    registry.clone(),
                    value["protocol_id"].as_i64().unwrap() as i32,
                    key.clone(),
                ));
            }
        }
        let live: Vec<_> = include_str!("fixtures/registries.tsv")
            .lines()
            .map(|line| {
                let parts: Vec<_> = line.split('\t').collect();
                (
                    parts[0].to_owned(),
                    parts[1].parse().unwrap(),
                    parts[2].to_owned(),
                )
            })
            .collect();
        entries.retain(|(registry, _, _)| !live.iter().any(|(key, _, _)| registry == key));
        entries.extend(live);
        Self { entries }
    }
}
impl crate::codec::RegistryContext for Context {
    fn entry_id(&self, registry: &Identifier, entry: &Identifier) -> Option<i32> {
        self.entries
            .iter()
            .find(|(r, _, e)| r == registry.as_str() && e == entry.as_str())
            .map(|(_, id, _)| *id)
    }
    fn entry_key(&self, registry: &Identifier, id: i32) -> Option<Identifier> {
        self.entries
            .iter()
            .find(|(r, i, _)| r == registry.as_str() && *i == id)
            .map(|(_, _, key)| Identifier::parse(key).unwrap())
    }
    fn has_tag(&self, _: &Identifier, _: &Identifier) -> bool {
        true
    }
}

fn bytes(hex: &str) -> Vec<u8> {
    let hex = hex.trim();
    (0..hex.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap())
        .collect()
}
fn check<T: Wire>(name: &str, hex: &str) -> T {
    let expected = bytes(hex);
    let context = Context::new();
    let mut r = Reader::with_context(&expected, &context);
    let value = T::decode(&mut r).unwrap_or_else(|e| panic!("{name}: {e}"));
    r.finish().unwrap_or_else(|e| panic!("{name}: {e}"));
    let mut w = Writer::with_context(&context);
    value
        .encode(&mut w)
        .unwrap_or_else(|e| panic!("{name}: {e}"));
    assert_eq!(w.into_inner(), expected, "{name}");
    value
}
