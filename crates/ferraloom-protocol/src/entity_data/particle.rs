macro_rules! record {
    ($name:ident { $($field:ident:$ty:ty),* }) => {
        #[derive(Clone, Debug, PartialEq)]
        pub struct $name { $(pub $field:$ty),* }
        impl Wire for $name {
            fn decode(r: &mut Reader<'_>) -> Result<Self> { Ok(Self { $($field:r.read()?),* }) }
            fn encode(&self, w: &mut Writer<'_>) -> Result<()> { $(w.write(&self.$field)?;)* Ok(()) }
        }
    };
}
