    pub fn by_id(id: &str) -> Option<Self> {
        let short = id.strip_prefix("minecraft:").unwrap_or(id);
        Self::ALL
            .into_iter()
            .find(|rule| rule.definition().id.strip_prefix("minecraft:") == Some(short))
    }
