import java.nio.file.*;

/** Boxed Java float equality, hashCode and compare observations, retaining raw input bits. */
public final class FloatValues {
    static final int[] FLOATS = {0,0x80000000,0x3f800000,0xbf800000,1,0x80000001,0x007fffff,0x00800000,
        0x3fc00000,0x7f7fffff,0xff7fffff,0x7f800000,0xff800000,0x7fc00000,0x7f800001,0x7fc01234,0xff800001,0xffc01234};
    static final long[] DOUBLES = {0,0x8000000000000000L,0x3ff0000000000000L,0xbff0000000000000L,1,0x8000000000000001L,
        0x000fffffffffffffL,0x0010000000000000L,0x3ff8000000000000L,0x7fefffffffffffffL,0xffefffffffffffffL,
        0x7ff0000000000000L,0xfff0000000000000L,0x7ff8000000000000L,0x7ff0000000000001L,0x7ff800123456789aL,
        0xfff0000000000001L,0xfff800123456789aL};
    public static void main(String[] args) throws Exception {
        var out=new StringBuilder("// Generated by tests/java/crafting/FloatValues.java using Java Float/Double.\n");
        out.append("const FLOAT_HASHES: &[(u32, i32)] = &[\n");
        for(int bits:FLOATS) out.append(String.format("    (0x%08x, %d),\n",bits,Float.hashCode(Float.intBitsToFloat(bits))));
        out.append("];\nconst DOUBLE_HASHES: &[(u64, i32)] = &[\n");
        for(long bits:DOUBLES) out.append(String.format("    (0x%016x, %d),\n",bits,Double.hashCode(Double.longBitsToDouble(bits))));
        out.append("];\nconst FLOAT_COMPARISONS: &[(u32, u32, bool, i8)] = &[\n");
        for(int a:FLOATS) for(int b:FLOATS) {
            Float x=Float.intBitsToFloat(a),y=Float.intBitsToFloat(b);
            out.append(String.format("    (0x%08x, 0x%08x, %s, %d),\n",a,b,x.equals(y),Integer.signum(Float.compare(x,y))));
        }
        out.append("];\nconst DOUBLE_COMPARISONS: &[(u64, u64, bool, i8)] = &[\n");
        for(long a:DOUBLES) for(long b:DOUBLES) {
            Double x=Double.longBitsToDouble(a),y=Double.longBitsToDouble(b);
            out.append(String.format("    (0x%016x, 0x%016x, %s, %d),\n",a,b,x.equals(y),Integer.signum(Double.compare(x,y))));
        }
        out.append("];\n");
        Files.writeString(Path.of(args[0]),out);
        System.out.println("Float vectors: 36 hash codes, 648 equality/order pairs");
    }
}
